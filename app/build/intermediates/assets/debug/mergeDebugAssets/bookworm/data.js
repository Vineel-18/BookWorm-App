// ── Dynamic delivery date helper ─────────────────────────────
// Returns "Mon, 15 Sep" style date N days from today
function _edd(daysAhead) {
  const d = new Date();
  d.setDate(d.getDate() + daysAhead);
  return d.toLocaleDateString('en-IN', { weekday: 'short', day: 'numeric', month: 'short' });
}

